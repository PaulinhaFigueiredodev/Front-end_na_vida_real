// O let permite declarar variáveis que podem ter seus valores alterados posteriormente. Por exemplo:
let idade = 25;
idade = 30;

console.log(idade); // Saída: 30

// O const permite declarar variáveis que não podem ter seus valores alterados posteriormente. Por exemplo:
const nome = 'Paula';

// Isso causará um erro, pois não é possível alterar o valor de uma variável declarada com const.
// Para visualizar o erro, você pode descomentar a linha abaixo:
// nome = 'Figueiredo'; 
console.log(nome);
